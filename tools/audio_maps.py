#!/usr/bin/env python3
"""Batch the C++ audio aligner, preserving demos and writing its readable runtime table."""
import argparse
import json
import shutil
import subprocess
from pathlib import Path

# Places come from the request call sites and map headers, rather than guessed soundtrack titles.
PLACES = [
    "field", "maps_7a_bc", "ending", "maps_47_99", "final_boss", "map_c4",
    "maps_46_d2", "battle", "maps_c7_cc", "tower", "maps_18_bd", "victory",
    "defeat", "title", "jingle_15", "jingle_16", "map_2f",
]
PAIRS = [(n, n, "original_" + PLACES[n - 1]) for n in range(1, 18)] + [
    (137 + n, n, PLACES[n - 1]) for n in range(1, 18)
] + [(163, 9, "song_9_coda"), (178, 15, "jingle_15_alias")]


WEAK = {
    2: "shorter WSC bass gates", 6: "shorter WSC bass gates", 9: "bass octave and voice/gate differences",
    10: "shorter WSC gates", 11: "shorter WSC gates", 16: "second part differs; wave silent",
    17: "WSC slot 4 rests through most of the phrase",
    139: "shorter WSC bass gates", 141: "shorter WSC bass gates", 143: "shorter WSC bass gates",
    144: "WSC first voice has different notes/octaves", 146: "bass octave and voice/gate differences",
    147: "shorter WSC gates", 148: "shorter WSC gates", 151: "changed voicing and shorter WSC gates",
    153: "second part differs; wave silent", 154: "WSC slot 4 rests through most of the phrase",
    163: "finite song 9 variant; bass octave and voice/gate differences",
}


def anchors(values):
    return "{" + ", ".join("{" + f"{w:g}, {g:g}" + "}" for w, g in values) + "}"


def entry(m):
    return (f"    {{{m['wsc']}, {m['gb']}, {anchors(m['anchors'])}, {m['slope']:g}, "
            f"{m['loop_start']}, {m['loop_ticks']}, {m['gb_loop_ticks']}, {m['loop_phase']:g}, "
            f"{anchors(m['loop_anchors'])}, "
            "{" + ", ".join(map(str, m['voices'])) + "}, " + str(m['clock_slot']) + "},")


def write_table(rows, path):
    table = ["// Generated by tools/audio_maps.py using sawgod-audio-spike align.",
             "// Exact pitch agreement: GB pulse 1 / pulse 2 / wave, over two WSC loops (finite songs: all notes).",
             "// Requests 135-137 are load-time GB transcriptions. Other unmapped records are silence or effects."]
    for m in rows:
        agreement = "/".join(f"{x:.1f}" if count else "silent" for x, count in zip(m['exact'], m['counts']))
        note = (" " + WEAK[m['wsc']] + ".") if m['wsc'] in WEAK else ""
        table += [f"    // {m['place'].replace('_', ' ')} ({m['wsc']}/{m['gb']}): {agreement}%.{note}", entry(m)]
    # These cues are transcribed, so their clock maps are exact and need no pitch alignment.
    for ws, voices, clock in [(135, [4, 6, 5], 4), (136, [1, 0, 2], 0), (137, [1, 2, 0], 0)]:
        table += [f"    // Transcribed event cue {ws}: WSC pitch/duration sequence, GB voices.",
                  entry(dict(wsc=ws, gb=ws-117, anchors=[(0, 1), (1, 2)], slope=1,
                             loop_start=0, loop_ticks=0, gb_loop_ticks=0, loop_phase=0,
                             loop_anchors=[], voices=voices, clock_slot=clock))]
    contents = "\n".join(table) + "\n"
    formatter = shutil.which("clang-format")
    if formatter:
        wrapped = "const GbSongMap kMaps[] = {\n" + contents + "};\n"
        formatted = subprocess.run([formatter], input=wrapped, capture_output=True, text=True, check=True).stdout
        contents = "\n".join(formatted.splitlines()[1:-1]) + "\n"
    path.write_text(contents, encoding="utf-8", newline="")


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("wsc_rom", type=Path)
    p.add_argument("gb_rom", type=Path)
    p.add_argument("inputs", type=Path)
    p.add_argument("--frame", type=int, default=2880)
    p.add_argument("--tool", type=Path, default=Path("build/linux-release/sawgod-audio-spike"))
    p.add_argument("--demos", type=Path, required=True)
    p.add_argument("--scratch", type=Path, default=Path("tmp/audio_maps/final"))
    p.add_argument("--table", type=Path, default=Path("src/app/gb_song_maps.inc"))
    args = p.parse_args()
    args.demos.mkdir(parents=True, exist_ok=True)
    args.scratch.mkdir(parents=True, exist_ok=True)
    rows = []
    for ws, gb, place in PAIRS:
        wav = args.demos / f"wsc{ws:03}_gb{gb:02}_{place}.wav"
        if wav.exists():
            version = 1
            while wav.with_name(wav.stem + f"_v{version}.wav").exists():
                version += 1
            shutil.copy2(wav, wav.with_name(wav.stem + f"_v{version}.wav"))
        data = args.scratch / f"{ws}.json"
        log = args.scratch / f"{ws}.log"
        cmd = [str(args.tool.resolve()), "align", str(args.wsc_rom), str(args.gb_rom),
               str(args.inputs), str(args.frame), str(ws), str(gb), str(wav), str(data)]
        with log.open("w", encoding="utf-8", newline="") as f:
            subprocess.run(cmd, stdout=f, stderr=subprocess.STDOUT, check=True)
        m = json.loads(data.read_text(encoding="utf-8"))
        m['place'] = place
        rows.append(m)
        agreement = "/".join(f"{x:.1f}" if count else "silent" for x, count in zip(m['exact'], m['counts']))
        print(f"{ws}/{gb} {place}: {agreement}%", flush=True)
    write_table(rows, args.table)
    (args.scratch / "maps.json").write_text(json.dumps(rows, indent=2) + "\n", encoding="utf-8", newline="")


if __name__ == "__main__":
    main()
