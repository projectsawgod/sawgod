#!/usr/bin/env python3
"""font_bake.py - compile a pixel font into the game's glyph table (src/engine/font_m5x7.inc).

  font_bake.py [--font ref/fonts/m5x7.ttf] [--size 16]

The port's variable-width text (game/text_render.h) uses m5x7 by Daniel Linssen (CC0),
drawn unmodified at the game's native pixels. This renders each character at the font's 1:1
size and writes, per character, its advance and 9 rows of 8 pixels (bit 7 = leftmost) from the cap top
(row 0) down to the second descender row (row 8): rows 0-6 sit on the WSC glyph rows of a tile, 7-8 hang
below. The output is committed (the font is CC0); rerun only to change the font or the character set.
"""
import argparse
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
CHARS = [chr(c) for c in range(0x20, 0x7F)] + list("…éèêëàâäôöûüçñōūĀāŌ")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", type=Path, default=ROOT / "ref" / "fonts" / "m5x7.ttf")
    ap.add_argument("--size", type=int, default=16)
    ap.add_argument("--out", type=Path, default=ROOT / "src" / "engine" / "font_m5x7.inc")
    a = ap.parse_args()
    f = ImageFont.truetype(str(a.font), a.size)
    cap_top = f.getbbox("H")[1]
    lines = ["// Generated by tools/font_bake.py from m5x7 by Daniel Linssen (CC0) -- do not edit.",
             "// {codepoint, advance, rows 0-8 from the cap top (bit 7 = leftmost pixel)}", "// clang-format off"]
    missing = []
    for ch in CHARS:
        m = Image.new("1", (16, 24), 0)
        d = ImageDraw.Draw(m)
        d.fontmode = "1"
        d.text((0, 0), ch, font=f, fill=1)
        if ch != " " and m.getbbox() is None:
            missing.append(ch)
            continue
        rows = []
        for r in range(9):
            bits = 0
            for x in range(8):
                if m.getpixel((x, cap_top + r)):
                    bits |= 0x80 >> x
            rows.append(bits)
        for x in range(8, 16):  # nothing may be wider than a cell
            if any(m.getpixel((x, y)) for y in range(24)):
                print(f"font_bake: {ch!r} is wider than 8 pixels", file=sys.stderr)
        adv = int(round(f.getlength(ch)))
        lines.append(f"{{0x{ord(ch):04X}, {adv}, {{{', '.join(f'0x{b:02X}' for b in rows)}}}}},")
    lines.append("// clang-format on")
    a.out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="")
    print(f"font_bake: {len(CHARS) - len(missing)} glyphs -> {a.out}" +
          (f" (not in the font: {''.join(missing)})" if missing else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
