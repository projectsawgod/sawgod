#!/usr/bin/env python3
"""font_bake_silver.py - bake the Silver pixel font into glyph tables for the ROM screen.

  font_bake_silver.py [--font ref/fonts/Silver.ttf]

Silver by Poppy Works (CC BY 4.0) draws the ROM screen, which comes up before any
ROM is loaded and so can't use the game's own font. Silver's pixel grid is 100 units with 1900 units per em, so
it is rendered at 19 px, one font pixel per output pixel. Two tables are written (both committed; the TTF is
not):

  src/engine/font_silver.inc          every glyph in the font (the whole font, so the
                                      ROM screen's strings can change without a rebake)
  src/engine/font_silver_prompts.inc  Silver's gamepad/keyboard/mouse prompt glyphs (U+2460-24ED, arrows,
                                      keyboard symbols), for the later controller icons; not wired yet

Each glyph: {codepoint, advance, x, y, w, h, first row}: x/y place the glyph's ink box relative to the pen
position and the line top; rows are uint32 bit masks (bit 31 = leftmost pixel) in a shared row array.
Rerun only for a new version of the font.
"""
import argparse
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
SIZE = 19
PROMPTS = (list(range(0x2460, 0x2477)) + list(range(0x2481, 0x24EE)) + list(range(0x2190, 0x219A)) +
           [0x2328, 0x232B, 0x238B])
CREDIT = "Silver by Poppy Works (https://poppyworks.itch.io/silver), CC BY 4.0"


def bake(font, cps, name, out, cmap):
    pad, base = 8, 32
    ascent, _ = font.getmetrics()
    rows, entries, missing = [], [], []
    for cp in cps:
        ch = chr(cp)
        if cp != 0x20 and cp not in cmap:
            missing.append(ch)
            continue
        im = Image.new("1", (64, 64), 0)
        d = ImageDraw.Draw(im)
        d.fontmode = "1"
        d.text((pad, base), ch, font=font, fill=1, anchor="ls")
        adv = int(round(font.getlength(ch)))
        box = im.getbbox()
        if box is None:
            entries.append((cp, adv, 0, 0, 0, 0, len(rows)))
            continue
        x0, y0, x1, y1 = box
        w, h = x1 - x0, y1 - y0
        if w > 32:
            sys.exit(f"font_bake_silver: U+{cp:04X} is {w} px wide (max 32)")
        first = len(rows)
        for y in range(y0, y1):
            bits = 0
            for x in range(x0, x1):
                if im.getpixel((x, y)):
                    bits |= 0x80000000 >> (x - x0)
            rows.append(bits)
        # y: from the line top (the ascent line) to the ink box top
        entries.append((cp, adv, x0 - pad, y0 - (base - ascent), w, h, first))
    lines = [f"// Generated by tools/font_bake_silver.py from {CREDIT} -- do not edit.",
             f"// {name}: {{codepoint, advance, x, y, w, h, first row}}; then the rows (bit 31 = leftmost pixel).",
             "// clang-format off",
             f"#define SILVER_GLYPHS_{name.upper()} \\"]
    lines += [f"    {{0x{e[0]:04X}, {e[1]}, {e[2]}, {e[3]}, {e[4]}, {e[5]}, {e[6]}}}, \\" for e in entries]
    lines.append("")
    lines.append(f"#define SILVER_ROWS_{name.upper()} \\")
    for i in range(0, len(rows), 8):
        lines.append("    " + " ".join(f"0x{r:08X}u," for r in rows[i:i + 8]) + " \\")
    lines.append("")
    lines.append("// clang-format on")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="")
    print(f"font_bake_silver: {len(entries)} glyphs, {len(rows)} rows -> {out.relative_to(ROOT)}" +
          (f" (not in the font: {''.join(missing)})" if missing else ""))
    return not missing


def font_cmap(path):
    import struct
    b = path.read_bytes()
    n = struct.unpack(">H", b[4:6])[0]
    tabs = {b[12 + 16 * i:16 + 16 * i].decode("latin-1"): struct.unpack(">II", b[20 + 16 * i:28 + 16 * i])
            for i in range(n)}
    o = tabs["cmap"][0]
    cps = set()
    for i in range(struct.unpack(">H", b[o + 2:o + 4])[0]):
        _, _, off = struct.unpack(">HHI", b[o + 4 + 8 * i:o + 12 + 8 * i])
        s = o + off
        if struct.unpack(">H", b[s:s + 2])[0] == 12:
            for g in range(struct.unpack(">I", b[s + 12:s + 16])[0]):
                a, z, _ = struct.unpack(">III", b[s + 16 + 12 * g:s + 28 + 12 * g])
                cps.update(range(a, z + 1))
    return cps


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", type=Path, default=ROOT / "ref" / "fonts" / "Silver.ttf")
    a = ap.parse_args()
    font = ImageFont.truetype(str(a.font), SIZE, layout_engine=ImageFont.Layout.BASIC)
    cmap = font_cmap(a.font)
    text = sorted({cp for cp in cmap if cp >= 0x20} | {0x20})
    ok = bake(font, text, "text", ROOT / "src" / "engine" / "font_silver.inc", cmap)
    ok &= bake(font, PROMPTS, "prompts", ROOT / "src" / "engine" / "font_silver_prompts.inc", cmap)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
